import clipping from 'polygon-clipping';
import {writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import {canalRows,canalBridges} from '../src/town-layout.js';

const rectangle=(x,z,w,d)=>[[[x-w/2,z-d/2],[x+w/2,z-d/2],[x+w/2,z+d/2],[x-w/2,z+d/2]]];
function circle(x,z,r,segments=64){return [Array.from({length:segments},(_,i)=>[x+Math.cos(i*2*Math.PI/segments)*r,z+Math.sin(i*2*Math.PI/segments)*r])];}
function path(points,width){
  const polygons=points.map(([x,z])=>circle(x,z,width/2,24));
  for(let i=1;i<points.length;i++){
    const [x,z]=points[i-1],[a,b]=points[i],d=Math.hypot(a-x,b-z),dx=-(b-z)/d*width/2,dz=(a-x)/d*width/2;
    polygons.push([[[x+dx,z+dz],[a+dx,b+dz],[a-dx,b-dz],[x-dx,z-dz]]]);
  }
  return polygons;
}
export function buildSurfaces(){
  const land=[circle(-14,24,13.4),circle(14,24,13.4),rectangle(0,17,17,20),rectangle(0,24,30,12),circle(-34,13,13),circle(0,32,12.6),rectangle(-26,19,20,9),rectangle(-18,33.5,8,9)];
  land.push(rectangle(0,44.5,7.2,9),rectangle(0,68,82,42));
  const roads=[rectangle(0,17,3.7,17),rectangle(0,24,32,3.7),circle(-14,24,7.7),circle(14,24,7.7),
    ...path([[-34,13],[-29,18],[-22,21],[-14,24]],3.1),...path([[-18,28],[-18,34]],2.4),
    ...path([[0,24],[0,29]],3.8),...path([[5,26],[10,31]],2.5)];
  roads.push(...path([[0,26],[5.8,27],[5.8,37.5],[0,39],[0,51],[0,85]],3.6));
  for(const z of [51,60.3,65.7,72.3,77.7,85])roads.push(rectangle(0,z,76,2.6));
  for(const x of [-36,-25,-15,15,25,36])roads.push(rectangle(x,68,2.6,34));
  // Polygon union removes internal faces rather than hiding z-fighting with depth bias.
  const canals=canalRows.map(z=>rectangle(0,z,84,3.1)),bridges=canalRows.flatMap(z=>canalBridges.map(x=>rectangle(x,z,3.3,3.5)));
  return {land:clipping.union(clipping.difference(clipping.union(...land),...canals),...bridges),roads:clipping.union(clipping.difference(clipping.union(...roads),...canals),...bridges)};
}
if(process.argv[1]===fileURLToPath(import.meta.url)){
  await writeFile(new URL('../src/surface-data.js',import.meta.url),'// Generated by npm run build:surfaces. Edit scripts/build-surfaces.mjs.\nexport const surfaces='+JSON.stringify(buildSurfaces())+';\n');
  console.log('Built continuous land and road surfaces.');
}
