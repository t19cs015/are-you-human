const templateCache=[];
const escape=value=>value.replace(/[.*+?^${}()|[\]\\]/g,'\\$&');
for(const [source,target] of Object.entries(english)){
  if(!source.includes('${')||!target.includes('${'))continue;
  const tokens=[...source.matchAll(/\$\{[^}]+\}/g)].map(match=>match[0]);
  if(!tokens.length||tokens.some(token=>!target.includes(token)))continue;
  let pattern='',last=0;
  for(const match of source.matchAll(/\$\{[^}]+\}/g)){pattern+=escape(source.slice(last,match.index))+'([\\s\\S]+?)';last=match.index+match[0].length;}
  pattern+=escape(source.slice(last));
  templateCache.push({regex:new RegExp('^'+pattern+'$'),tokens,target});
}
const fragments=Object.entries(english).filter(([source])=>!source.includes('${')&&source.length>=2).sort((a,b)=>b[0].length-a[0].length);
export function translateText(value,language='en'){
  if(language!=='en'||typeof value!=='string')return value;
  const finish=text=>text.replaceAll('。','. ').replaceAll('、',', ').replace(/\s+([,.!?])/g,'$1').trimEnd();
  let match=value.match(/^(.+)の記憶を開く$/);if(match)return 'Open memory: '+translateText(match[1],language);
  match=value.match(/^(\d+)番目の場所に記憶を置く$/);if(match)return `Place a memory in slot ${match[1]}`;
  if(!/[ぁ-んァ-ヶ一-龠]/.test(value))return finish(value);
  if(Object.hasOwn(english,value))return finish(english[value]);
  for(const item of templateCache){const match=value.match(item.regex);if(!match)continue;let result=item.target;item.tokens.forEach((token,index)=>{result=result.replace(token,match[index+1]);});return finish(result);}
  let result=value;
  for(const [source,target] of fragments)if(result.includes(source))result=result.split(source).join(target);
  return finish(result);
}
